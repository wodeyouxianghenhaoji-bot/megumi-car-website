"""Build the browser catalog from reviewed UTF-8 translation rows (no network)."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
LANGS = ['en', 'ar', 'nl', 'fr', 'de', 'it', 'pt', 'ru', 'es', 'ja']
catalog = {lang: {} for lang in ['zh'] + LANGS}
for number, line in enumerate((ROOT / 'tools/locales.tsv').read_text('utf8').splitlines(), 1):
    if not line.strip():
        continue
    parts = line.split('|')
    assert len(parts) == len(LANGS) + 1, (number, len(parts))
    source, *translations = parts
    assert source not in catalog['zh'], (number, source)
    catalog['zh'][source] = source
    for lang, text in zip(LANGS, translations):
        assert text.strip(), (number, lang)
        catalog[lang][source] = text

